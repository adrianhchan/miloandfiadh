import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { ORIGIN, REVIEWED, books, pages } from './seo-data.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const esc = value => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
const absoluteImage = filename => `${ORIGIN}/assets/images/${encodeURIComponent(filename)}`;
const organizationId = `${ORIGIN}/#organization`;
const websiteId = `${ORIGIN}/#website`;
const authorId = `${ORIGIN}/about-the-author.html#author`;
const seriesId = `${ORIGIN}/#book-series`;
const ref = id => ({ '@id': id });

export function graphFor(page) {
  const url = ORIGIN + page.path;
  const graph = [
    { '@type': 'Organization', '@id': organizationId, name: 'Milo and Fiadh', legalName: '2021076 Ontario Corporation', url: ORIGIN + '/', email: 'hi@miloandfiadh.com', logo: { '@type': 'ImageObject', url: absoluteImage('Logo Nav.png'), width: 682, height: 682 }, sameAs: ['https://www.instagram.com/miloandfiadh', 'https://www.tiktok.com/@miloandfiadh', 'https://www.youtube.com/@MiloAndFiadh'] },
    { '@type': 'WebSite', '@id': websiteId, url: ORIGIN + '/', name: 'Milo and Fiadh', alternateName: 'Milo & Fiadh', inLanguage: 'en', publisher: ref(organizationId) },
    { '@type': 'Person', '@id': authorId, name: 'Anita Cheng', url: ORIGIN + '/about-the-author.html' },
    { '@type': 'BookSeries', '@id': seriesId, name: 'Milo and Fiadh', url: ORIGIN + '/#collection', author: ref(authorId), inLanguage: 'en', hasPart: books.map(book => ref(`${ORIGIN}/${book.file}#book`)) },
    { '@type': page.type, '@id': url + '#webpage', url, name: page.title, description: page.description, inLanguage: 'en', isPartOf: ref(websiteId), publisher: ref(organizationId), primaryImageOfPage: { '@type': 'ImageObject', url: absoluteImage(page.image) } },
  ];
  const webpage = graph[4];
  if (page.asin) {
    const bookId = url + '#book';
    webpage.mainEntity = ref(bookId);
    graph.push({ '@type': 'Book', '@id': bookId, name: page.name, url, description: page.description, image: absoluteImage(page.image), author: ref(authorId), inLanguage: 'en', isPartOf: ref(seriesId), mainEntityOfPage: ref(webpage['@id']), identifier: { '@type': 'PropertyValue', propertyID: 'ASIN', value: page.asin }, sameAs: `https://www.amazon.com/dp/${page.asin}` });
  } else if (page.file === 'index.html') {
    webpage.mainEntity = ref(ORIGIN + '/#collection');
    graph.push({ '@type': 'ItemList', '@id': ORIGIN + '/#collection', name: 'Milo and Fiadh book collection', itemListElement: books.map((book, index) => ({ '@type': 'ListItem', position: index + 1, name: book.name, url: `${ORIGIN}/${book.file}` })) });
  } else if (page.type === 'AboutPage') {
    webpage.mainEntity = ref(authorId);
  } else if (page.file === 'info-for-parents.html') {
    webpage.about = ref(seriesId);
  }
  if (page.label) {
    webpage.breadcrumb = ref(url + '#breadcrumb');
    graph.push({ '@type': 'BreadcrumbList', '@id': url + '#breadcrumb', itemListElement: [{ '@type': 'ListItem', position: 1, name: 'Home', item: ORIGIN + '/' }, { '@type': 'ListItem', position: 2, name: page.label, item: url }] });
  }
  return { '@context': 'https://schema.org', '@graph': graph };
}

export function updateSeo() {
  for (const page of pages) {
    const file = resolve(root, page.file);
    let html = readFileSync(file, 'utf8');
    html = html.replace(/\n    <!-- SEO metadata: generated.*?<!-- \/SEO metadata -->/s, '');
    html = html.replace(/<title>.*?<\/title>/s, `<title>${esc(page.title)}</title>`);
    html = html.replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${esc(page.description)}">`);
    const url = ORIGIN + page.path;
    const metadata = [
      '<!-- SEO metadata: generated by scripts/update-seo.mjs -->',
      `<link rel="canonical" href="${url}">`,
      '<meta name="robots" content="index, follow, max-image-preview:large">',
      '<meta property="og:site_name" content="Milo and Fiadh">',
      '<meta property="og:type" content="website">',
      `<meta property="og:title" content="${esc(page.title)}">`,
      `<meta property="og:description" content="${esc(page.description)}">`,
      `<meta property="og:url" content="${url}">`,
      `<meta property="og:image" content="${absoluteImage(page.image)}">`,
      `<meta property="og:image:alt" content="${esc(page.imageAlt)}">`,
      '<meta name="twitter:card" content="summary_large_image">',
      `<meta name="twitter:title" content="${esc(page.title)}">`,
      `<meta name="twitter:description" content="${esc(page.description)}">`,
      `<meta name="twitter:image" content="${absoluteImage(page.image)}">`,
      `<meta name="twitter:image:alt" content="${esc(page.imageAlt)}">`,
      ...(page.asin || page.file === 'index.html' ? [`<link rel="preload" as="image" href="assets/images/${page.image}" fetchpriority="high">`] : []),
      `<script type="application/ld+json">\n${JSON.stringify(graphFor(page), null, 2).replaceAll('<', '\\u003c')}\n    </script>`,
      '<!-- /SEO metadata -->',
    ].join('\n    ');
    html = html.replace('</title>', `</title>\n    ${metadata}`);
    html = html.replace(/    <!-- Existing site analytics\. -->\s*<script async src="https:\/\/www.googletagmanager.com\/gtag\/js\?id=G-6GFF7V2JGX"><\/script>\s*<script>.*?<\/script>/s, '    <script src="analytics.js" defer></script>');
    for (const [label, destination] of Object.entries({ 'Info for parents': 'info-for-parents.html', 'About the author': 'about-the-author.html', Privacy: 'privacy.html', 'Terms &amp; Conditions': 'terms-and-conditions.html' })) {
      html = html.replaceAll(`href="#">${label}</a>`, `href="${destination}">${label}</a>`);
    }
    writeFileSync(file, html);
  }
  const sitemap = pages.map(page => `  <url><loc>${ORIGIN + page.path}</loc><lastmod>${REVIEWED}</lastmod></url>`).join('\n');
  writeFileSync(resolve(root, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${sitemap}\n</urlset>\n`);
  writeFileSync(resolve(root, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${ORIGIN}/sitemap.xml\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) updateSeo();
